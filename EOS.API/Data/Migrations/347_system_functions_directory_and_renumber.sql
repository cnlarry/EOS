/* ---------- 2. 收口断言（不论走哪条分支都必须成立） ---------- */
IF (SELECT COUNT(*) FROM dbo.MODULES WHERE M_IDX IN (230101, 230102)) <> 2
    THROW 54710, N'230101/230102 应各有一行。', 1;
IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2315)
    THROW 54711, N'2315 应已退役删除（编号不复用）。', 1;
IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2301 AND (M_URL IS NOT NULL OR MASTER_TABLE IS NOT NULL))
    THROW 54712, N'2301 应为纯目录：M_URL 与 MASTER_TABLE 必须都为空。', 1;
IF NOT EXISTS (SELECT 1 FROM dbo.V_MODULE_NODE WHERE M_IDX = 2301 AND NODE_KIND = N'DIRECTORY')
    THROW 54713, N'形态视图里 2301 不是 DIRECTORY（多半是 URL/主表没清干净）。', 1;
IF NOT EXISTS (SELECT 1 FROM dbo.V_MODULE_NODE WHERE M_IDX = 230101 AND NODE_KIND = N'CUSTOMPAGE')
    THROW 54714, N'形态视图里 230101 不是 CUSTOMPAGE。', 1;
IF NOT EXISTS (SELECT 1 FROM dbo.V_MODULE_NODE WHERE M_IDX = 230102 AND NODE_KIND = N'CUSTOMPAGE')
    THROW 54715, N'形态视图里 230102 不是 CUSTOMPAGE。', 1;
IF (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 230101) <> (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 2301)
    THROW 54716, N'230101 的组授权行数应与 2301 一致（镜像）。', 1;
IF (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 2315) + (SELECT COUNT(*) FROM dbo.SYSDD WHERE M_IDX = 2315) > 0
    THROW 54717, N'2315 的授权行应已清理。', 1;
IF (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 230102) < 1
    THROW 54718, N'230102 应至少有一行组授权（自 2315 镜像）。', 1;
IF (SELECT COUNT(*) FROM dbo.MODULES WHERE ISNULL(APPROVE_ENABLED, 0) = 1) < 170
    THROW 54719, N'批核入口集合不应因本次改判而缩小（ADR-035 的 170 个声明模块）。', 1;
PRINT N'== migration 347 收口：2301=系统功能目录；230101=模块管理；230102=模块分组；2315 退役 ==';
GO
