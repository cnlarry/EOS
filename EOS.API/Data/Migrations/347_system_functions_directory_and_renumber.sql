--
-- 三条口径：
--   ① 2301 变**纯目录**：M_URL 与 MASTER_TABLE **必须同时清空**——只清 URL 会被
--      V_MODULE_NODE 判成 WORKBENCH（"URL 留空但有主表即默认落统一工作台"），形态到不了 DIRECTORY；
--   ② 原内容重编号用**新建行 + 删旧行**（不是 sp_rename）：旧行的形态外配置残留不带走，
--      且 2315 这个号退役后按纪律不复用；
--   ③ 授权行**逐列镜像**：以当前 2301/2315 的 SYSDH/SYSDD 行为源，按主体逐行复制到新编号；
--      2301 自己那份保留（目录的可见性锚点）。不照抄历史迁移的列清单——CI 已下线、
--      FORM_ADJUST_TAG 早已改名 MODULE_CONFIG_TAG。
--
-- 幂等：目标行已存在即整段跳过；授权镜像带 NOT EXISTS 防重；断言失败即整支回滚（DbUp 一脚本一事务）。
-- ============================================================================
