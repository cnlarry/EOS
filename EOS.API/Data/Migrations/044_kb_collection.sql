-- Knowledge base for assistant RAG (SQL Server vectors first, Qdrant as escape).
-- KB_COLLECTION: one row per corpus (embedding model + dimension recorded;
-- changing the model means a new collection + rebuild, never mixed spaces).
-- KB_DOCUMENT: ingested document versions (content-hash idempotent; old versions
-- retained as deleted tombstones, vectors removed with their chunks).
-- KB_CHUNK: retrieval unit (text + VECTOR embedding + source ordering).
-- Visibility is collection-level tiers (ALL/CONSULTANT/OPS), enforced in API;
-- the vector store is a derived index, never the source of truth.

SET NOCOUNT ON;

DECLARE @GUARD NVARCHAR(400) = N'本脚本只能在 EOS.ERP 数据库内执行，当前库为 ' + DB_NAME() + N'。';
IF DB_NAME() <> N'EOS.ERP'
    THROW 50000, @GUARD, 1;

BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.KB_COLLECTION', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.KB_COLLECTION (
        [COLLECTION_ID] NVARCHAR(50) NOT NULL CONSTRAINT [PK_KB_COLLECTION] PRIMARY KEY,
        [TITLE] NVARCHAR(200) NOT NULL,
        [EMBEDDING_MODEL] NVARCHAR(100) NOT NULL,
        [DIMENSION] INT NOT NULL CONSTRAINT [DF_KB_COLLECTION_DIM] DEFAULT (1024),
        [DEFAULT_VISIBILITY] NVARCHAR(20) NOT NULL CONSTRAINT [DF_KB_COLLECTION_VIS] DEFAULT (N'ALL'),
        [CREATE_DATE] DATETIME2(3) NOT NULL CONSTRAINT [DF_KB_COLLECTION_CREATED] DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT [CK_KB_COLLECTION_VIS] CHECK ([DEFAULT_VISIBILITY] IN (N'ALL', N'CONSULTANT', N'OPS'))
    );
END

IF OBJECT_ID(N'dbo.KB_DOCUMENT', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.KB_DOCUMENT (
        [DOC_ID] BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_KB_DOCUMENT] PRIMARY KEY,
        [COLLECTION_ID] NVARCHAR(50) NOT NULL
            CONSTRAINT [FK_KB_DOCUMENT_COLLECTION] REFERENCES dbo.KB_COLLECTION ([COLLECTION_ID]),
        [TITLE] NVARCHAR(200) NOT NULL,
        [SOURCE_URI] NVARCHAR(500) NULL,
        [CONTENT_HASH] CHAR(64) NOT NULL,
        [VISIBILITY] NVARCHAR(20) NOT NULL CONSTRAINT [DF_KB_DOCUMENT_VIS] DEFAULT (N'ALL'),
        [STATUS] NVARCHAR(20) NOT NULL CONSTRAINT [DF_KB_DOCUMENT_STATUS] DEFAULT (N'active'),
        [VERSION] INT NOT NULL CONSTRAINT [DF_KB_DOCUMENT_VERSION] DEFAULT (1),
        [CREATE_BY] NVARCHAR(50) NULL,
        [CREATE_DATE] DATETIME2(3) NOT NULL CONSTRAINT [DF_KB_DOCUMENT_CREATED] DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT [CK_KB_DOCUMENT_VIS] CHECK ([VISIBILITY] IN (N'ALL', N'CONSULTANT', N'OPS')),
        CONSTRAINT [CK_KB_DOCUMENT_STATUS] CHECK ([STATUS] IN (N'active', N'deleted'))
    );
    CREATE INDEX [IX_KB_DOCUMENT_COLLECTION]
        ON dbo.KB_DOCUMENT ([COLLECTION_ID], [STATUS], [CONTENT_HASH]);
END

IF OBJECT_ID(N'dbo.KB_CHUNK', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.KB_CHUNK (
        [CHUNK_ID] BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_KB_CHUNK] PRIMARY KEY,
        [DOC_ID] BIGINT NOT NULL
            CONSTRAINT [FK_KB_CHUNK_DOCUMENT] REFERENCES dbo.KB_DOCUMENT ([DOC_ID]) ON DELETE CASCADE,
        [SERIAL_NO] INT NOT NULL,
        [CONTENT] NVARCHAR(MAX) NOT NULL,
        [EMBEDDING] VECTOR(1024) NULL,
        CONSTRAINT [UQ_KB_CHUNK_DOC_SERIAL] UNIQUE ([DOC_ID], [SERIAL_NO])
    );
    CREATE INDEX [IX_KB_CHUNK_DOC] ON dbo.KB_CHUNK ([DOC_ID], [SERIAL_NO]);
END

-- Seed the first collection (general org knowledge, BGE- space).
IF NOT EXISTS (SELECT 1 FROM dbo.KB_COLLECTION WHERE COLLECTION_ID = N'kb_general')
BEGIN
    INSERT INTO dbo.KB_COLLECTION (COLLECTION_ID, TITLE, EMBEDDING_MODEL, DIMENSION, DEFAULT_VISIBILITY)
    VALUES (N'kb_general', N'组织级共享知识', N'bge-m3@1', 1024, N'ALL');
END

COMMIT TRANSACTION;

PRINT N'[044] 知识库表已就绪（KB_COLLECTION / KB_DOCUMENT / KB_CHUNK）。';
