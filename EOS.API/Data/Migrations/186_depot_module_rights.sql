-- ============================================================================
-- EOS.ERP migration 187: 库位主档与库存策略的授权行
-- ----------------------------------------------------------------------------
-- 模块行只决定了"菜单里有这一项"；没有授权行，任何用户（含管理员）都进不去。
--
-- 授权**逐列复制同域兄弟模块 110306 仓库资料**的现有行，只为新模块替换 M_IDX ——
-- 不硬编码 33 个标志位：库位主档与库存策略和仓库资料同属仓库域，管理深度也是同一层，
-- 授权口径本就应当一致；复制既有行还能自动跟随该模块后续的权限调整。
--
-- 组权限（SYSDH）与个人权限（SYSDD）分别复制。
-- 幂等：目标行已存在即跳过。
-- 回滚：DELETE 本迁移为 110309 / 110310 写入的授权行。
-- ============================================================================

SET NOCOUNT ON;

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;

DECLARE @GUARD_MESSAGE NVARCHAR(400) = N'本脚本只能在 EOS.ERP 数据库内执行，当前库为 ' + DB_NAME() + N'。';
IF DB_NAME() <> N'EOS.ERP'
    THROW 51600, @GUARD_MESSAGE, 1;

IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110306)
    THROW 51601, N'参照模块 110306 仓库资料不存在，迁移中止。', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110309)
   OR NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110310)
    THROW 51602, N'库位主档 / 库存策略模块尚未注册，迁移中止。', 1;

/* ---------- 组权限 ---------- */
INSERT INTO dbo.SYSDH
    (G_IDX, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
     ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
     DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
     DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
     APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
     FORM_DESIGN_TAG, FORM_ADJUST_TAG)
SELECT h.G_IDX, s.M_IDX, h.EXEC_TAG, h.ADDNEW_TAG, h.DELETE_TAG, h.EDIT_TAG, h.REPORT_TAG, h.COST_TAG,
       h.SETUP_TAG, h.SECRECY_TAG, h.ENDCASE_TAG, h.UNENDCASE_TAG, h.OTHER1_TAG, h.OTHER2_TAG,
       h.OTHER3_TAG, h.OTHER4_TAG, h.DENY_VIEW_FIELD_MASTER, h.DENY_VIEW_FIELD_DETAIL,
       h.DENY_NEW_FIELD_MASTER, h.DENY_NEW_FIELD_DETAIL, h.DENY_MODI_FIELD_MASTER, h.DENY_MODI_FIELD_DETAIL,
       h.DATA_FILTER, h.CI, h.OPERFLAG, h.APPROVE_TAG, h.DEAPPROVE_TAG, h.FILE_VIEW_TAG, h.FILE_UPDA_TAG,
       h.FILE_EDIT_TAG, h.FILE_DELE_TAG, h.FORM_DESIGN_TAG, h.FORM_ADJUST_TAG
FROM dbo.SYSDH h
CROSS JOIN (VALUES (110309), (110310)) AS s(M_IDX)
WHERE h.M_IDX = 110306
  AND NOT EXISTS (SELECT 1 FROM dbo.SYSDH x WHERE x.G_IDX = h.G_IDX AND x.M_IDX = s.M_IDX);

PRINT N'== 已复制组权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';

/* ---------- 个人权限 ---------- */
INSERT INTO dbo.SYSDD
    (USER_ID, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
     ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
     DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
     DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
     APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
     FORM_DESIGN_TAG, FORM_ADJUST_TAG)
SELECT d.USER_ID, s.M_IDX, d.EXEC_TAG, d.ADDNEW_TAG, d.DELETE_TAG, d.EDIT_TAG, d.REPORT_TAG, d.COST_TAG,
       d.SETUP_TAG, d.SECRECY_TAG, d.ENDCASE_TAG, d.UNENDCASE_TAG, d.OTHER1_TAG, d.OTHER2_TAG,
       d.OTHER3_TAG, d.OTHER4_TAG, d.DENY_VIEW_FIELD_MASTER, d.DENY_VIEW_FIELD_DETAIL,
       d.DENY_NEW_FIELD_MASTER, d.DENY_NEW_FIELD_DETAIL, d.DENY_MODI_FIELD_MASTER, d.DENY_MODI_FIELD_DETAIL,
       d.DATA_FILTER, d.CI, d.OPERFLAG, d.APPROVE_TAG, d.DEAPPROVE_TAG, d.FILE_VIEW_TAG, d.FILE_UPDA_TAG,
       d.FILE_EDIT_TAG, d.FILE_DELE_TAG, d.FORM_DESIGN_TAG, d.FORM_ADJUST_TAG
FROM dbo.SYSDD d
CROSS JOIN (VALUES (110309), (110310)) AS s(M_IDX)
WHERE d.M_IDX = 110306
  AND NOT EXISTS (SELECT 1 FROM dbo.SYSDD x WHERE x.USER_ID = d.USER_ID AND x.M_IDX = s.M_IDX);

PRINT N'== 已复制个人权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';

/* ---------- 收口断言 ---------- */
IF NOT EXISTS (SELECT 1 FROM dbo.SYSDH WHERE M_IDX IN (110309, 110310))
    THROW 51603, N'新模块没有组权限行，迁移中止。', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.SYSDD WHERE M_IDX IN (110309, 110310))
    THROW 51604, N'新模块没有个人权限行，迁移中止。', 1;

/* 授权口径必须与参照模块一致：每个新模块的 (组, 权限位) 组合数不得少于参照模块 */
DECLARE @refGroups INT = (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 110306);
DECLARE @newGroups INT = (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 110309);

IF @newGroups < @refGroups
    THROW 51605, N'新模块的组权限行数少于参照模块，迁移中止。', 1;

PRINT N'== 收口：110309 / 110310 的组权限与个人权限已按 110306 的口径复制 ==';
