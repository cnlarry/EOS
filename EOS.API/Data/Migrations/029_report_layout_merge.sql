-- ============================================================================
-- EOS.ERP migration 029: P3 storage convergence — REPORT_LAYOUT four-in-one,
-- dead-column removal, 2202-2204 taken offline
-- ----------------------------------------------------------------------------
-- Background: the four report layout tables (REPORT_HEADER/REPORT_FOOTER/REPORT_TAIL/
-- REPORT_IMAGE) are merged into a single layout resource table REPORT_LAYOUT; the old
-- tables are physically dropped after moving existing data. Footer semantics merge into
-- REPORT.FOOTER_TEXT. Dead REPORT columns (REPORT_PATH/DEFAULT_PAPER/DEFAULT_PRINTER/IMAGE_ID)
-- are removed. The 2202/2203/2204 admin pages are taken offline (M_TAG=0).
--
-- Design:
--   REPORT_LAYOUT (LAYOUT_ID, KIND, LAYOUT_DESC, CONTENT, IMAGE_PATH, IS_DEFAULT, audit cols)
--   KIND = HEADER / TAIL / FOOTER / IMAGE
--   CONTENT = text (header JSON / footer plain text / tail plain text)
--   IMAGE_PATH = image path (LOGO)
--   REPORT.HEADER_ID/TAIL_ID keep semantics, pointing to REPORT_LAYOUT.LAYOUT_ID
--   REPORT.FOOTER_TEXT kept (not moved into the layout table)
--   Report-level header JSON: {"companyName":"...","companyNameEn":"...","headerText":"..."}
-- Idempotent: IF OBJECT_ID guards — skips when source table already gone, safe to re-run.
-- ============================================================================

SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;

DECLARE @GUARD_MESSAGE NVARCHAR(400) = N'本脚本只能在 EOS.ERP 数据库内执行，当前库为 ' + DB_NAME() + N'。';
IF DB_NAME() <> N'EOS.ERP'
    THROW 50000, @GUARD_MESSAGE, 1;

BEGIN TRANSACTION;

-- 1. 建 REPORT_LAYOUT（不存在才建）
IF OBJECT_ID('dbo.REPORT_LAYOUT') IS NULL
BEGIN
    CREATE TABLE dbo.REPORT_LAYOUT (
        [LAYOUT_ID] NVARCHAR(50) NOT NULL CONSTRAINT [PK_REPORT_LAYOUT] PRIMARY KEY,
        [KIND] NVARCHAR(20) NOT NULL,
        [LAYOUT_DESC] NVARCHAR(100) NULL,
        [CONTENT] NVARCHAR(MAX) NULL,
        [IMAGE_PATH] NVARCHAR(500) NULL,
        [IS_DEFAULT] BIT NOT NULL CONSTRAINT [DF_REPORT_LAYOUT_DEFAULT] DEFAULT (0),
        [CREATE_PERSON] NCHAR(40) NULL,
        [CREATE_DATE] DATETIME2 NOT NULL CONSTRAINT [DF_REPORT_LAYOUT_CREATED] DEFAULT (SYSDATETIME()),
        [LAST_UPDATE_BY] NCHAR(40) NULL,
        [LAST_UPDATE_DATE] DATETIME2 NULL
    );
    CREATE INDEX [IX_REPORT_LAYOUT_KIND] ON dbo.REPORT_LAYOUT ([KIND]);
END

-- 2. 搬移 REPORT_HEADER → REPORT_LAYOUT（KIND=HEADER，CONTENT=JSON；仅当源表仍存在）
IF OBJECT_ID('dbo.REPORT_HEADER') IS NOT NULL
BEGIN
    INSERT INTO dbo.REPORT_LAYOUT (LAYOUT_ID, KIND, LAYOUT_DESC, CONTENT, IMAGE_PATH, IS_DEFAULT, CREATE_PERSON, CREATE_DATE)
    SELECT LTRIM(RTRIM(h.HEADER_ID)), N'HEADER', LTRIM(RTRIM(ISNULL(h.HEADER_NAME,h.HEADER_ID))),
           N'{"companyName":"' + REPLACE(ISNULL(LTRIM(RTRIM(h.COMPANY_NAME)),''),'"','\"') + N'","companyNameEn":"' + REPLACE(ISNULL(LTRIM(RTRIM(h.COMPANY_NAME_EN)),''),'"','\"') + N'","headerText":"' + REPLACE(ISNULL(LTRIM(RTRIM(h.HEADER_TEXT)),''),'"','\"') + N'"}',
           LTRIM(RTRIM(ISNULL(h.LOGO_PATH,''))), 1, N'EOS-MIG-029', SYSDATETIME()
    FROM dbo.REPORT_HEADER h WITH (NOLOCK)
    WHERE NOT EXISTS (SELECT 1 FROM dbo.REPORT_LAYOUT l WHERE l.LAYOUT_ID = h.HEADER_ID);
END

-- 3. 搬移 REPORT_TAIL → REPORT_LAYOUT（KIND=TAIL，CONTENT=TAIL_TEXT；仅当源表仍存在）
IF OBJECT_ID('dbo.REPORT_TAIL') IS NOT NULL
BEGIN
    INSERT INTO dbo.REPORT_LAYOUT (LAYOUT_ID, KIND, LAYOUT_DESC, CONTENT, IS_DEFAULT, CREATE_PERSON, CREATE_DATE)
    SELECT LTRIM(RTRIM(t.TAIL_ID)), N'TAIL', LTRIM(RTRIM(ISNULL(t.TAIL_NAME,t.TAIL_ID))),
           LTRIM(RTRIM(ISNULL(t.TAIL_TEXT,''))), 1, N'EOS-MIG-029', SYSDATETIME()
    FROM dbo.REPORT_TAIL t WITH (NOLOCK)
    WHERE NOT EXISTS (SELECT 1 FROM dbo.REPORT_LAYOUT l WHERE l.LAYOUT_ID = t.TAIL_ID);
END

-- 4. REPORT_IMAGE 0 行，不搬移；REPORT_FOOTER 死表不搬移（页尾由 REPORT.FOOTER_TEXT 承载）

-- 5. 物理删除四表（存在才删）
IF OBJECT_ID('dbo.REPORT_HEADER') IS NOT NULL DROP TABLE dbo.REPORT_HEADER;
IF OBJECT_ID('dbo.REPORT_FOOTER') IS NOT NULL DROP TABLE dbo.REPORT_FOOTER;
IF OBJECT_ID('dbo.REPORT_TAIL') IS NOT NULL DROP TABLE dbo.REPORT_TAIL;
IF OBJECT_ID('dbo.REPORT_IMAGE') IS NOT NULL DROP TABLE dbo.REPORT_IMAGE;

-- 6. REPORT 删死列（存在才删）
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.REPORT') AND name = 'REPORT_PATH')
    ALTER TABLE dbo.REPORT DROP COLUMN [REPORT_PATH];
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.REPORT') AND name = 'DEFAULT_PAPER')
    ALTER TABLE dbo.REPORT DROP COLUMN [DEFAULT_PAPER];
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.REPORT') AND name = 'DEFAULT_PRINTER')
    ALTER TABLE dbo.REPORT DROP COLUMN [DEFAULT_PRINTER];
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.REPORT') AND name = 'IMAGE_ID')
    ALTER TABLE dbo.REPORT DROP COLUMN [IMAGE_ID];

-- 7. 2202/2203/2204 菜单节点隐藏（M_TAG 已为 0 则跳过 REMARK 追加）
UPDATE dbo.MODULES SET M_TAG = 0,
    REMARK = LTRIM(RTRIM(ISNULL(REMARK,''))) + N'；ADR-009 P3 下线（2026-08-30）：打印版式设置页随表物理删除，页眉/表尾由 REPORT_LAYOUT 统一承载'
WHERE M_IDX IN (2202, 2203, 2204) AND ISNULL(M_TAG,1) = 1;

-- 8. WORKBENCH 快照防御清理
DELETE FROM dbo.WORKBENCH_MODULE_DIRTY WHERE MODULE_ID IN (2202, 2203, 2204);
DELETE FROM dbo.WORKBENCH_DEFINITION_SNAPSHOT WHERE MODULE_ID IN (2202, 2203, 2204);

-- 9. 审计计数
SELECT 'REPORT_LAYOUT' AS KIND, COUNT(*) AS CNT FROM dbo.REPORT_LAYOUT;
SELECT 'REPORT_LEGACY_TABLES' AS KIND, COUNT(*) AS CNT FROM sys.tables WHERE name IN ('REPORT_HEADER','REPORT_FOOTER','REPORT_TAIL','REPORT_IMAGE');

COMMIT TRANSACTION;