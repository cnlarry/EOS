-- ----------------------------------------------------------------------------
-- 129802 是报表承载页时代留下的自定义承载页（M_URL=/bom-expand，主表
-- BOM_STRU_M），菜单可见。它的功能与 1204 产品BOM表重复，系统不再需要这个
-- 页面；同时它的 M_P_IDX 仍指向 274 已删除的 XX98 目录 1298，属于悬空父指针，
-- 保留只会让系统菜单与模块管理树继续按两套规则呈现同一行数据。
--
-- 退役范围：
--   1. 129802 的报表族：REPORT(BOM_List) 及其排序 / 用户状态 / 收件箱 / 订阅，
--      以及用户打印偏好 SYSQR；
--   2. 权限行：SYSDD / SYSDH（含按钮权限行）；
--   3. 模块配置与运行时状态：MODULE_BUSINESS_ACTION / MODULE_VALIDATION_RULE /
--      MODULE_FORM_LAYOUT / MODULE_FORM_TAB / MODULE_GROUPS /
--      WORKBENCH_MODULE_DIRTY / WORKBENCH_DEFINITION_SNAPSHOT /
--      WORKBENCH_IDEMPOTENCY / IMPORT_MAPPING / FORM_CHOOSER_SOURCE_MEMO；
--   4. 单据遗留：ATTACHMENT / WF_APPROVE；
--   5. 指向它的字段浏览链接、TABLES.T_REMARK 与表级 MS_Description 中的
--      "129802:BOM展开表；" 条目；
--   6. MODULES 行本身（物理删除）。
--
-- 保留：BOM_STRU_M / BOM_STRU_D 是 1204 产品BOM表的主/明细表，不随本模块退役；
-- AUDIT_EVENT 等历史审计按既有口径保留，供追溯。
--
-- 幂等：所有删除按存在性判断，重复执行是空操作；前置条件与后置不变量都在
-- 事务外/内显式断言，口径变化时中止而不是"尽力而为"。
-- ============================================================================

