-- 425：金额显示口径固定两位小数
--
-- 金额是会计口径：800 必须显示成 800.00。存量里有 143 个金额字段配的是
-- 去尾零格式（0.## / #.## / 0.# / #.#），显示结果与打印件不一致；统一改为固定两位。
-- 显示格式是定义快照的一部分，改完必须重发布，故同时把相关模块标脏。

BEGIN TRAN;

SELECT DISTINCT f.T_ID
INTO #AMOUNT_TABLES
FROM dbo.FIELDS AS f
WHERE f.NUMERIC_ROLE = N'AMOUNT'
  AND LTRIM(RTRIM(ISNULL(f.DISPLAY_FORMAT, N''))) IN (N'0.##', N'#.##', N'0.#', N'#.#');

UPDATE f
SET f.DISPLAY_FORMAT = N'#,##0.00'
FROM dbo.FIELDS AS f
JOIN #AMOUNT_TABLES AS t ON t.T_ID = f.T_ID
WHERE f.NUMERIC_ROLE = N'AMOUNT'
  AND LTRIM(RTRIM(ISNULL(f.DISPLAY_FORMAT, N''))) IN (N'0.##', N'#.##', N'0.#', N'#.#');

INSERT INTO dbo.WORKBENCH_MODULE_DIRTY (M_IDX, DIRTY_TAG, LAST_MODIFIED_BY, LAST_MODIFIED_AT)
SELECT DISTINCT m.M_IDX, 1, N'DbUp', SYSDATETIME()
FROM dbo.MODULES AS m
WHERE (m.MASTER_TABLE IN (SELECT T_ID FROM #AMOUNT_TABLES)
       OR ISNULL(m.DETAIL_TABLE, N'') IN (SELECT T_ID FROM #AMOUNT_TABLES))
  AND NOT EXISTS (SELECT 1 FROM dbo.WORKBENCH_MODULE_DIRTY AS d WHERE d.M_IDX = m.M_IDX);

DROP TABLE #AMOUNT_TABLES;

COMMIT;
GO
