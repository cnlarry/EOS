-- ============================================================================
-- EOS.ERP migration 284: 日志管理定制页按 23 段重编号（退役 110112 → 2313）
-- ----------------------------------------------------------------------------
--  来源：ADR-029（用户反馈入口与一键日志打包）§2.1.1；283 把该页挂在
--        基本参数（根 11 / 父 1101）下，与「定制页一律落 /admin/*，而 /admin/*
--        都属 23 系统管理」的既有惯例不符。
--
--  为什么另出 284 而不是改 283：283 已在本库落库（台账 2026-09-29 20:34:11），
--  改一个已执行脚本的内容既不会重跑、也让"脚本内容与台账"对不上后来人；
--  编号是排序键、文件名是判重身份，重编号本身就是一次新的元数据变更。
--
--  为什么 2313 挂 2311 数据表维护（而不是 23 本级）：
--  23 本级是管理型页面（模块管理 / 用户组 / 用户权限 / 单据性质 / 工作任务），
--  而 2311 下挂的恰是运维·数据类页面（2302 数据表字段维护 20、2303 读写数据表信息 30、
--  2307 数据库备份 99）；日志管理与它们同类，SORT_IDX 取 40 落在 30 与 99 之间。
--
--  **编号一旦退役就不复用也不保留**：本脚本收口时断言 110112 在 MODULES /
--  SYSDH / SYSDD 三处均无残留。
--
--  幂等：三种库形态都收敛到同一终态——① 本库（283 已建 110112）；② 未跑 283 的库
--  （无 110112，2313 新建）；③ 全新库（283 先建 110112，再由本脚本搬运）。
--  授权行按 (主体, M_IDX) 不存在才插，可重复执行。
-- ============================================================================
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;

DECLARE @GuardMessage NVARCHAR(400) = N'本脚本只能在 EOS.ERP 数据库内执行，当前库为 ' + DB_NAME() + N'。';
IF DB_NAME() <> N'EOS.ERP'
    THROW 51700, @GuardMessage, 1;

-- 权限镜像的参照模块：02313 的读/打包权限锚定在 02313 上，而 283 那版锚在 11 与 110111，
-- 故重建口径必须同时参照两者，授权集合才只增不减（不因重编号而少授权）。
IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 11)
    THROW 51710, N'参照模块 11 基本参数不存在，迁移中止（日志管理的接口权限锚点以它为准）。', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2311)
    THROW 51711, N'参照模块 2311 数据表维护不存在，迁移中止（日志管理页挂在它下面）。', 1;

IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2313 AND M_URL <> N'/admin/logs')
    THROW 51712, N'模块 2313 已被占用（URL 不是 /admin/logs），迁移中止：编号不回收、不复用。', 1;

BEGIN TRANSACTION;

/* ---------- 1. 模块登记：23 系统管理 → 2311 数据表维护 → 2313 日志管理 ---------- */
IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2313)
BEGIN
    INSERT INTO dbo.MODULES (M_IDX, M_DESC, M_URL, M_P_IDX, M_ROOT_IDX, SORT_IDX, M_TAG, MASTER_TABLE)
    VALUES (2313, N'日志管理', N'/admin/logs', 2311, 23, 40, 1, NULL);
    PRINT N'== 新增模块 2313 日志管理（/admin/logs，父 2311、根 23、序 40）==';
END
ELSE
    PRINT N'== 模块 2313 已存在，跳过登记 ==';

/* ---------- 2. 组权限：先按 283 的参照模块 110111 补（若它仍在），再按 11 重建 ---------- */
IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110111)
BEGIN
    INSERT INTO dbo.SYSDH
        (G_IDX, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
         ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
         DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
         DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
         APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
         FORM_DESIGN_TAG, MODULE_CONFIG_TAG)
    SELECT h.G_IDX, 2313, h.EXEC_TAG, h.ADDNEW_TAG, h.DELETE_TAG, h.EDIT_TAG, h.REPORT_TAG, h.COST_TAG,
           h.SETUP_TAG, h.SECRECY_TAG, h.ENDCASE_TAG, h.UNENDCASE_TAG, h.OTHER1_TAG, h.OTHER2_TAG,
           h.OTHER3_TAG, h.OTHER4_TAG, h.DENY_VIEW_FIELD_MASTER, h.DENY_VIEW_FIELD_DETAIL,
           h.DENY_NEW_FIELD_MASTER, h.DENY_NEW_FIELD_DETAIL, h.DENY_MODI_FIELD_MASTER, h.DENY_MODI_FIELD_DETAIL,
           h.DATA_FILTER, h.CI, h.OPERFLAG, h.APPROVE_TAG, h.DEAPPROVE_TAG, h.FILE_VIEW_TAG, h.FILE_UPDA_TAG,
           h.FILE_EDIT_TAG, h.FILE_DELE_TAG, h.FORM_DESIGN_TAG, h.MODULE_CONFIG_TAG
    FROM dbo.SYSDH h
    WHERE h.M_IDX = 110111
      AND NOT EXISTS (SELECT 1 FROM dbo.SYSDH x WHERE x.G_IDX = h.G_IDX AND x.M_IDX = 2313);
    PRINT N'== 已按 110111 补组权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';
END

INSERT INTO dbo.SYSDH
    (G_IDX, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
     ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
     DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
     DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
     APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
     FORM_DESIGN_TAG, MODULE_CONFIG_TAG)
SELECT h.G_IDX, 2313, h.EXEC_TAG, h.ADDNEW_TAG, h.DELETE_TAG, h.EDIT_TAG, h.REPORT_TAG, h.COST_TAG,
       h.SETUP_TAG, h.SECRECY_TAG, h.ENDCASE_TAG, h.UNENDCASE_TAG, h.OTHER1_TAG, h.OTHER2_TAG,
       h.OTHER3_TAG, h.OTHER4_TAG, h.DENY_VIEW_FIELD_MASTER, h.DENY_VIEW_FIELD_DETAIL,
       h.DENY_NEW_FIELD_MASTER, h.DENY_NEW_FIELD_DETAIL, h.DENY_MODI_FIELD_MASTER, h.DENY_MODI_FIELD_DETAIL,
       h.DATA_FILTER, h.CI, h.OPERFLAG, h.APPROVE_TAG, h.DEAPPROVE_TAG, h.FILE_VIEW_TAG, h.FILE_UPDA_TAG,
       h.FILE_EDIT_TAG, h.FILE_DELE_TAG, h.FORM_DESIGN_TAG, h.MODULE_CONFIG_TAG
FROM dbo.SYSDH h
WHERE h.M_IDX = 11
  AND NOT EXISTS (SELECT 1 FROM dbo.SYSDH x WHERE x.G_IDX = h.G_IDX AND x.M_IDX = 2313);

PRINT N'== 已按模块 11 补组权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';

/* ---------- 3. 个人权限：同口径（个人权限整表覆盖组权限，漏搬会直接少授权）---------- */
IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110111)
BEGIN
    INSERT INTO dbo.SYSDD
        (USER_ID, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
         ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
         DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
         DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
         APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
         FORM_DESIGN_TAG, MODULE_CONFIG_TAG)
    SELECT d.USER_ID, 2313, d.EXEC_TAG, d.ADDNEW_TAG, d.DELETE_TAG, d.EDIT_TAG, d.REPORT_TAG, d.COST_TAG,
           d.SETUP_TAG, d.SECRECY_TAG, d.ENDCASE_TAG, d.UNENDCASE_TAG, d.OTHER1_TAG, d.OTHER2_TAG,
           d.OTHER3_TAG, d.OTHER4_TAG, d.DENY_VIEW_FIELD_MASTER, d.DENY_VIEW_FIELD_DETAIL,
           d.DENY_NEW_FIELD_MASTER, d.DENY_NEW_FIELD_DETAIL, d.DENY_MODI_FIELD_MASTER, d.DENY_MODI_FIELD_DETAIL,
           d.DATA_FILTER, d.CI, d.OPERFLAG, d.APPROVE_TAG, d.DEAPPROVE_TAG, d.FILE_VIEW_TAG, d.FILE_UPDA_TAG,
           d.FILE_EDIT_TAG, d.FILE_DELE_TAG, d.FORM_DESIGN_TAG, d.MODULE_CONFIG_TAG
    FROM dbo.SYSDD d
    WHERE d.M_IDX = 110111
      AND NOT EXISTS (SELECT 1 FROM dbo.SYSDD x WHERE x.USER_ID = d.USER_ID AND x.M_IDX = 2313);
    PRINT N'== 已按 110111 补个人权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';
END

INSERT INTO dbo.SYSDD
    (USER_ID, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
     ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
     DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
     DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
     APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
     FORM_DESIGN_TAG, MODULE_CONFIG_TAG)
SELECT d.USER_ID, 2313, d.EXEC_TAG, d.ADDNEW_TAG, d.DELETE_TAG, d.EDIT_TAG, d.REPORT_TAG, d.COST_TAG,
       d.SETUP_TAG, d.SECRECY_TAG, d.ENDCASE_TAG, d.UNENDCASE_TAG, d.OTHER1_TAG, d.OTHER2_TAG,
       d.OTHER3_TAG, d.OTHER4_TAG, d.DENY_VIEW_FIELD_MASTER, d.DENY_VIEW_FIELD_DETAIL,
       d.DENY_NEW_FIELD_MASTER, d.DENY_NEW_FIELD_DETAIL, d.DENY_MODI_FIELD_MASTER, d.DENY_MODI_FIELD_DETAIL,
       d.DATA_FILTER, d.CI, d.OPERFLAG, d.APPROVE_TAG, d.DEAPPROVE_TAG, d.FILE_VIEW_TAG, d.FILE_UPDA_TAG,
       d.FILE_EDIT_TAG, d.FILE_DELE_TAG, d.FORM_DESIGN_TAG, d.MODULE_CONFIG_TAG
FROM dbo.SYSDD d
WHERE d.M_IDX = 11
  AND NOT EXISTS (SELECT 1 FROM dbo.SYSDD x WHERE x.USER_ID = d.USER_ID AND x.M_IDX = 2313);

PRINT N'== 已按模块 11 补个人权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';

/* ---------- 4. 退役旧编号：MODULES 有外键引用（报表/校验规则/业务动作），先查后删 ---------- */
IF EXISTS (SELECT 1 FROM dbo.REPORT WHERE M_IDX = 110112)
    THROW 51713, N'报表仍归属模块 110112，迁移中止（先迁移报表归属，不得连带删除）。', 1;

IF EXISTS (SELECT 1 FROM dbo.MODULE_VALIDATION_RULE WHERE M_IDX = 110112)
    THROW 51714, N'校验规则仍引用模块 110112，迁移中止。', 1;

IF EXISTS (SELECT 1 FROM dbo.MODULE_BUSINESS_ACTION WHERE M_IDX = 110112)
    THROW 51715, N'业务动作仍引用模块 110112，迁移中止。', 1;

IF EXISTS (SELECT 1 FROM dbo.SYSDH WHERE M_IDX = 110112)
BEGIN
    DELETE FROM dbo.SYSDH WHERE M_IDX = 110112;
    PRINT N'== 已退役模块 110112 的组权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';
END

IF EXISTS (SELECT 1 FROM dbo.SYSDD WHERE M_IDX = 110112)
BEGIN
    DELETE FROM dbo.SYSDD WHERE M_IDX = 110112;
    PRINT N'== 已退役模块 110112 的个人权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';
END

IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110112)
BEGIN
    DELETE FROM dbo.MODULES WHERE M_IDX = 110112;
    PRINT N'== 已退役模块 110112（编号不再保留、不再复用）==';
END

/* ---------- 5. 收口断言 ---------- */
IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2313 AND M_URL = N'/admin/logs'
                 AND M_P_IDX = 2311 AND M_ROOT_IDX = 23 AND ISNULL(M_TAG, 1) = 1)
    THROW 51716, N'模块 2313 未就位或其层级不是 23/2311，迁移中止。', 1;

IF EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 110112)
   OR EXISTS (SELECT 1 FROM dbo.SYSDH WHERE M_IDX = 110112)
   OR EXISTS (SELECT 1 FROM dbo.SYSDD WHERE M_IDX = 110112)
    THROW 51717, N'模块 110112 仍有残留（MODULES/SYSDH/SYSDD），迁移中止。', 1;

-- 重编号不得少授权：参照模块（11 与 110111）里的每个权限主体，新模块都要有对应行。
IF EXISTS (
        SELECT h.G_IDX FROM dbo.SYSDH h
        WHERE h.M_IDX IN (11, 110111)
          AND NOT EXISTS (SELECT 1 FROM dbo.SYSDH x WHERE x.G_IDX = h.G_IDX AND x.M_IDX = 2313))
    THROW 51718, N'模块 2313 的组权限少于参照模块（11 / 110111），迁移中止。', 1;

IF EXISTS (
        SELECT d.USER_ID FROM dbo.SYSDD d
        WHERE d.M_IDX IN (11, 110111)
          AND NOT EXISTS (SELECT 1 FROM dbo.SYSDD x WHERE x.USER_ID = d.USER_ID AND x.M_IDX = 2313))
    THROW 51719, N'模块 2313 的个人权限少于参照模块（11 / 110111），迁移中止。', 1;

COMMIT TRANSACTION;

DECLARE @GroupRows INT = (SELECT COUNT(*) FROM dbo.SYSDH WHERE M_IDX = 2313);
DECLARE @UserRows INT = (SELECT COUNT(*) FROM dbo.SYSDD WHERE M_IDX = 2313);
PRINT N'== 收口：日志管理已重编号为 2313（根 23 / 父 2311），授权 ' 
    + CONVERT(NVARCHAR(10), @GroupRows) + N' 组 / ' + CONVERT(NVARCHAR(10), @UserRows) + N' 人；110112 已退役 ==';
