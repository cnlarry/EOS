-- ============================================================================
-- EOS.ERP migration 291: 工作助手模型表（dbo.ASSISTANT_MODEL）+ 模块 3102 登记
-- ----------------------------------------------------------------------------
--  来源：ADR-030（工作助手管理面）§3 / §4 / §5（批 3）
--
--  **这张表里没有密钥**：只存 API Key 的**环境变量名**（API_KEY_ENV_VAR）。
--  密钥由管理员在界面上输入一次，服务端写进进程环境变量（立即生效）并持久化到用户级
--  环境变量（重启后仍在），数据库里从头到尾没有它——备份与导出因此不含任何密钥。
--
--  **不预置任何行**：表为空时助手照旧用 appsettings 里那套配置（行为与现在完全一致），
--  管理员可以"把当前配置纳管"成第一条记录，也可以直接新增。这样上线不需要一次性切换。
--
--  **同一时刻只有一条"当前模型"**：靠筛选唯一索引 UX_ASSISTANT_MODEL_ACTIVE 保证，
--  不是靠应用代码自觉——并发切换若靠代码去保证，很容易留下两条 IS_ACTIVE=1。
--
--  **新增"温度/最大 token/供应商"三个字段是全新的**：此前的配置里一个都没有
--  （`AssistantSettings` 只有 BaseUrl/ApiKey/Model/TimeoutSeconds）。也就是说 3102 提供的是
--  新的调节能力，而不是"把已有配置搬上界面"。
--
--  幂等：建表与模块登记都按"不存在才做"；授权行按"不存在才插"。可重复执行。
-- ============================================================================
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;

DECLARE @GuardMessage NVARCHAR(400) = N'本脚本只能在 EOS.ERP 数据库内执行，当前库为 ' + DB_NAME() + N'。';
IF DB_NAME() <> N'EOS.ERP'
    THROW 51700, @GuardMessage, 1;

IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 31)
    THROW 51701, N'根组 31 工作助手管理不存在，迁移中止（先跑迁移 288）。', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 2306)
    THROW 51702, N'参照模块 2306 用户权限设定不存在，迁移中止（授权镜像以它为准）。', 1;

BEGIN TRANSACTION;

/* ---------- 1. 模型表 ---------- */
IF OBJECT_ID(N'dbo.ASSISTANT_MODEL', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ASSISTANT_MODEL (
        [MODEL_ID]        INT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_ASSISTANT_MODEL] PRIMARY KEY,
        [DISPLAY_NAME]    NVARCHAR(100) NOT NULL,
        [PROVIDER]        NVARCHAR(50)  NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_PROVIDER] DEFAULT (N'deepseek'),
        [MODEL_NAME]      NVARCHAR(100) NOT NULL,
        [BASE_URL]        NVARCHAR(300) NOT NULL,
        [API_KEY_ENV_VAR] NVARCHAR(100) NOT NULL,
        [TIMEOUT_SECONDS] INT NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_TIMEOUT] DEFAULT (300),
        [TEMPERATURE]     DECIMAL(3,2) NULL,
        [MAX_TOKENS]      INT NULL,
        [IS_ACTIVE]       BIT NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_ACTIVE] DEFAULT (0),
        [ENABLED]         BIT NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_ENABLED] DEFAULT (1),
        [SORT_IDX]        INT NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_SORT] DEFAULT (0),
        [REMARK]          NVARCHAR(200) NULL,
        [CREATED_AT]      DATETIME2(3) NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_CREATED] DEFAULT (SYSUTCDATETIME()),
        [UPDATED_AT]      DATETIME2(3) NOT NULL CONSTRAINT [DF_ASSISTANT_MODEL_UPDATED] DEFAULT (SYSUTCDATETIME()),
        [CREATED_BY]      NVARCHAR(50) NULL,
        [UPDATED_BY]      NVARCHAR(50) NULL,
        CONSTRAINT [CK_ASSISTANT_MODEL_TIMEOUT] CHECK ([TIMEOUT_SECONDS] BETWEEN 10 AND 3600),
        CONSTRAINT [CK_ASSISTANT_MODEL_TEMPERATURE] CHECK ([TEMPERATURE] IS NULL OR ([TEMPERATURE] >= 0 AND [TEMPERATURE] <= 2)),
        CONSTRAINT [CK_ASSISTANT_MODEL_MAXTOKENS] CHECK ([MAX_TOKENS] IS NULL OR ([MAX_TOKENS] BETWEEN 1 AND 200000)),
        -- 空的环境变量名等于"没有密钥来源"，直接在库层面挡掉
        CONSTRAINT [CK_ASSISTANT_MODEL_ENVVAR] CHECK (LEN(LTRIM(RTRIM([API_KEY_ENV_VAR]))) > 0)
    );

    -- 筛选唯一索引：至多一行 IS_ACTIVE = 1
    CREATE UNIQUE INDEX [UX_ASSISTANT_MODEL_ACTIVE] ON dbo.ASSISTANT_MODEL ([IS_ACTIVE]) WHERE [IS_ACTIVE] = 1;

    PRINT N'== 新建表 dbo.ASSISTANT_MODEL ==';
END
ELSE
    PRINT N'== 表 dbo.ASSISTANT_MODEL 已存在，跳过 ==';

/* ---------- 2. 子模块 3102 模型与用量 ---------- */
IF NOT EXISTS (SELECT 1 FROM dbo.MODULES WHERE M_IDX = 3102)
BEGIN
    INSERT INTO dbo.MODULES (M_IDX, M_DESC, M_URL, M_P_IDX, M_ROOT_IDX, SORT_IDX, M_TAG, MASTER_TABLE)
    VALUES (3102, N'模型与用量', N'/admin/assistant/models', 31, 31, 20, 1, NULL);
    PRINT N'== 新增模块 3102 模型与用量（/admin/assistant/models）==';
END
ELSE
    PRINT N'== 模块 3102 已存在，跳过 ==';

/* ---------- 3. 组权限镜像（照 2306 的口径）---------- */
INSERT INTO dbo.SYSDH
    (G_IDX, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
     ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
     DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
     DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
     APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
     FORM_DESIGN_TAG, MODULE_CONFIG_TAG)
SELECT h.G_IDX, 3102, h.EXEC_TAG, h.ADDNEW_TAG, h.DELETE_TAG, h.EDIT_TAG, h.REPORT_TAG, h.COST_TAG,
       h.SETUP_TAG, h.SECRECY_TAG, h.ENDCASE_TAG, h.UNENDCASE_TAG, h.OTHER1_TAG, h.OTHER2_TAG,
       h.OTHER3_TAG, h.OTHER4_TAG, h.DENY_VIEW_FIELD_MASTER, h.DENY_VIEW_FIELD_DETAIL,
       h.DENY_NEW_FIELD_MASTER, h.DENY_NEW_FIELD_DETAIL, h.DENY_MODI_FIELD_MASTER, h.DENY_MODI_FIELD_DETAIL,
       h.DATA_FILTER, h.CI, h.OPERFLAG, h.APPROVE_TAG, h.DEAPPROVE_TAG, h.FILE_VIEW_TAG, h.FILE_UPDA_TAG,
       h.FILE_EDIT_TAG, h.FILE_DELE_TAG, h.FORM_DESIGN_TAG, h.MODULE_CONFIG_TAG
FROM dbo.SYSDH h
WHERE h.M_IDX = 2306
  AND NOT EXISTS (SELECT 1 FROM dbo.SYSDH x WHERE x.G_IDX = h.G_IDX AND x.M_IDX = 3102);

PRINT N'== 已镜像组权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';

/* ---------- 4. 个人权限镜像（admin 靠这一步才看得见新菜单）---------- */
INSERT INTO dbo.SYSDD
    (USER_ID, M_IDX, EXEC_TAG, ADDNEW_TAG, DELETE_TAG, EDIT_TAG, REPORT_TAG, COST_TAG, SETUP_TAG, SECRECY_TAG,
     ENDCASE_TAG, UNENDCASE_TAG, OTHER1_TAG, OTHER2_TAG, OTHER3_TAG, OTHER4_TAG,
     DENY_VIEW_FIELD_MASTER, DENY_VIEW_FIELD_DETAIL, DENY_NEW_FIELD_MASTER, DENY_NEW_FIELD_DETAIL,
     DENY_MODI_FIELD_MASTER, DENY_MODI_FIELD_DETAIL, DATA_FILTER, CI, OPERFLAG,
     APPROVE_TAG, DEAPPROVE_TAG, FILE_VIEW_TAG, FILE_UPDA_TAG, FILE_EDIT_TAG, FILE_DELE_TAG,
     FORM_DESIGN_TAG, MODULE_CONFIG_TAG)
SELECT d.USER_ID, 3102, d.EXEC_TAG, d.ADDNEW_TAG, d.DELETE_TAG, d.EDIT_TAG, d.REPORT_TAG, d.COST_TAG,
       d.SETUP_TAG, d.SECRECY_TAG, d.ENDCASE_TAG, d.UNENDCASE_TAG, d.OTHER1_TAG, d.OTHER2_TAG,
       d.OTHER3_TAG, d.OTHER4_TAG, d.DENY_VIEW_FIELD_MASTER, d.DENY_VIEW_FIELD_DETAIL,
       d.DENY_NEW_FIELD_MASTER, d.DENY_NEW_FIELD_DETAIL, d.DENY_MODI_FIELD_MASTER, d.DENY_MODI_FIELD_DETAIL,
       d.DATA_FILTER, d.CI, d.OPERFLAG, d.APPROVE_TAG, d.DEAPPROVE_TAG, d.FILE_VIEW_TAG, d.FILE_UPDA_TAG,
       d.FILE_EDIT_TAG, d.FILE_DELE_TAG, d.FORM_DESIGN_TAG, d.MODULE_CONFIG_TAG
FROM dbo.SYSDD d
WHERE d.M_IDX = 2306
  AND NOT EXISTS (SELECT 1 FROM dbo.SYSDD x WHERE x.USER_ID = d.USER_ID AND x.M_IDX = 3102);

PRINT N'== 已镜像个人权限 ' + CONVERT(NVARCHAR(10), @@ROWCOUNT) + N' 行 ==';

/* ---------- 5. 收口断言 ---------- */
IF OBJECT_ID(N'dbo.ASSISTANT_MODEL', N'U') IS NULL
    THROW 51703, N'表 dbo.ASSISTANT_MODEL 未就位，迁移中止。', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.MODULES
               WHERE M_IDX = 3102 AND M_P_IDX = 31 AND M_ROOT_IDX = 31
                 AND M_URL = N'/admin/assistant/models' AND M_TAG = 1)
    THROW 51704, N'模块 3102 未就位或 URL 不是 /admin/assistant/models，迁移中止。', 1;

-- 密钥列绝不该存在：用断言把这个意图固定下来，后人想加列时会先撞到这里
IF EXISTS (SELECT 1 FROM sys.columns
           WHERE object_id = OBJECT_ID(N'dbo.ASSISTANT_MODEL')
             AND name IN (N'API_KEY', N'APIKEY', N'SECRET', N'TOKEN'))
    THROW 51705, N'dbo.ASSISTANT_MODEL 里出现了疑似密钥列——密钥不入库（ADR-030 §3），迁移中止。', 1;

DECLARE @RefUsers INT = (SELECT COUNT(*) FROM dbo.SYSDD WHERE M_IDX = 2306);
DECLARE @NewUsers INT = (SELECT COUNT(*) FROM dbo.SYSDD WHERE M_IDX = 3102);
IF @NewUsers < @RefUsers
    THROW 51706, N'模块 3102 的个人权限行数少于参照模块 2306，迁移中止（admin 会看不到新菜单）。', 1;

COMMIT TRANSACTION;

PRINT N'== 收口：模型与用量（3102）已按 2306 的口径就位 ==';
