/*
 * 框架表的建立人/建立时间补齐 NOT NULL + DEFAULT。
 *
 * 迁移 451 把框架表上的同义列（CREATE_BY / CREATED_AT / CREATED_DATE）收进了统一命名，
 * `CREATED_BY` / `CREATED_TIME` 因此进入 `check-lifecycle-columns` 的“收紧组”口径：
 * 建立组必须 NOT NULL 且有 DEFAULT 约束（NULL 会让“谁建的、什么时候建的”失去兜底）。
 * 这四张表原先的可空列与缺省值在新名字下会被门禁判为违规，故在此补齐。
 *
 * 只动框架表，单据主表的建立组早已是 NOT NULL + DEFAULT。
 */

SET NOCOUNT ON;

-- 1) 建立人：先补空串（这四张表的建立人由应用层写入，历史空值按“未知”记空串）
UPDATE dbo.FIELD_DATASOURCE SET CREATED_BY = N'' WHERE CREATED_BY IS NULL;
UPDATE dbo.KB_DOCUMENT SET CREATED_BY = N'' WHERE CREATED_BY IS NULL;
UPDATE dbo.ASSISTANT_PROVIDER SET CREATED_BY = N'' WHERE CREATED_BY IS NULL;
UPDATE dbo.ASSISTANT_MODEL SET CREATED_BY = N'' WHERE CREATED_BY IS NULL;

-- 2) 建立人收紧为 NOT NULL（已是 NOT NULL 的表上重复执行无副作用）
ALTER TABLE dbo.FIELD_DATASOURCE ALTER COLUMN CREATED_BY nvarchar(100) NOT NULL;
ALTER TABLE dbo.KB_DOCUMENT ALTER COLUMN CREATED_BY nvarchar(100) NOT NULL;
ALTER TABLE dbo.ASSISTANT_PROVIDER ALTER COLUMN CREATED_BY nvarchar(100) NOT NULL;
ALTER TABLE dbo.ASSISTANT_MODEL ALTER COLUMN CREATED_BY nvarchar(100) NOT NULL;

-- 3) 建立人补 DEFAULT 约束（同名已存在则跳过，避免换库重跑时报重名）
IF NOT EXISTS (SELECT 1 FROM sys.default_constraints
               WHERE name = N'DF_FIELD_DATASOURCE_CREATED_BY'
                 AND parent_object_id = OBJECT_ID(N'dbo.FIELD_DATASOURCE'))
    ALTER TABLE dbo.FIELD_DATASOURCE ADD CONSTRAINT DF_FIELD_DATASOURCE_CREATED_BY DEFAULT (N'') FOR CREATED_BY;

IF NOT EXISTS (SELECT 1 FROM sys.default_constraints
               WHERE name = N'DF_KB_DOCUMENT_CREATED_BY'
                 AND parent_object_id = OBJECT_ID(N'dbo.KB_DOCUMENT'))
    ALTER TABLE dbo.KB_DOCUMENT ADD CONSTRAINT DF_KB_DOCUMENT_CREATED_BY DEFAULT (N'') FOR CREATED_BY;

IF NOT EXISTS (SELECT 1 FROM sys.default_constraints
               WHERE name = N'DF_ASSISTANT_PROVIDER_CREATED_BY'
                 AND parent_object_id = OBJECT_ID(N'dbo.ASSISTANT_PROVIDER'))
    ALTER TABLE dbo.ASSISTANT_PROVIDER ADD CONSTRAINT DF_ASSISTANT_PROVIDER_CREATED_BY DEFAULT (N'') FOR CREATED_BY;

IF NOT EXISTS (SELECT 1 FROM sys.default_constraints
               WHERE name = N'DF_ASSISTANT_MODEL_CREATED_BY'
                 AND parent_object_id = OBJECT_ID(N'dbo.ASSISTANT_MODEL'))
    ALTER TABLE dbo.ASSISTANT_MODEL ADD CONSTRAINT DF_ASSISTANT_MODEL_CREATED_BY DEFAULT (N'') FOR CREATED_BY;

-- 4) 审计落库时间补 DEFAULT（列本就 NOT NULL，写路径一直显式赋值；补默认只是让口径一致）
IF NOT EXISTS (SELECT 1 FROM sys.default_constraints
               WHERE name = N'DF_AUDIT_EVENT_CREATED_TIME'
                 AND parent_object_id = OBJECT_ID(N'dbo.AUDIT_EVENT'))
    ALTER TABLE dbo.AUDIT_EVENT ADD CONSTRAINT DF_AUDIT_EVENT_CREATED_TIME DEFAULT (SYSDATETIME()) FOR CREATED_TIME;
