-- ADR-007 M2：工作助手会话与消息表（EOS.ERP 唯一业务库，对象名全大写）。
-- 会话按 USER_ID 隔离（对齐 SYSDL 账号）；消息含 token/耗时/关联 ID，替代原网关用量汇总。
-- 审计：M3 接入工具调用（业务数据访问）时写 AUDIT_EVENT；M2 纯对话由本表自身留痕。

CREATE TABLE dbo.ASSISTANT_SESSION
(
    ID             BIGINT         IDENTITY (1, 1) NOT NULL,
    USER_ID        NVARCHAR(50)   NOT NULL,
    TITLE          NVARCHAR(200)  NOT NULL CONSTRAINT DF_ASSISTANT_SESSION_TITLE DEFAULT (N'新对话'),
    CREATED_AT     DATETIME2(3)   NOT NULL CONSTRAINT DF_ASSISTANT_SESSION_CREATED DEFAULT SYSUTCDATETIME(),
    LAST_ACTIVE_AT DATETIME2(3)   NOT NULL CONSTRAINT DF_ASSISTANT_SESSION_LAST_ACTIVE DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_ASSISTANT_SESSION PRIMARY KEY (ID)
);

CREATE INDEX IX_ASSISTANT_SESSION_USER_ACTIVE
    ON dbo.ASSISTANT_SESSION (USER_ID, LAST_ACTIVE_AT DESC);

CREATE TABLE dbo.ASSISTANT_MESSAGE
(
    ID               BIGINT        IDENTITY (1, 1) NOT NULL,
    SESSION_ID       BIGINT        NOT NULL,
    ROLE             TINYINT       NOT NULL, -- 1=USER 2=ASSISTANT 3=SYSTEM
    CONTENT          NVARCHAR(MAX) NOT NULL,
    MODEL_NAME       NVARCHAR(100) NULL,     -- 仅 ASSISTANT 行记录实际模型
    PROMPT_TOKENS    INT           NULL,
    COMPLETION_TOKENS INT          NULL,
    ELAPSED_MS       INT           NULL,
    CORRELATION_ID   NVARCHAR(128) NULL,
    CREATED_AT       DATETIME2(3)  NOT NULL CONSTRAINT DF_ASSISTANT_MESSAGE_CREATED DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_ASSISTANT_MESSAGE PRIMARY KEY (ID),
    CONSTRAINT FK_ASSISTANT_MESSAGE_SESSION FOREIGN KEY (SESSION_ID) REFERENCES dbo.ASSISTANT_SESSION (ID),
    CONSTRAINT CK_ASSISTANT_MESSAGE_ROLE CHECK (ROLE IN (1, 2, 3))
);

CREATE INDEX IX_ASSISTANT_MESSAGE_SESSION
    ON dbo.ASSISTANT_MESSAGE (SESSION_ID, ID);
