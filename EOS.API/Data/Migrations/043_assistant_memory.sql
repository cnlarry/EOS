-- Assistant cross-session memory L1/L2 (user-scoped, explicit only).
-- ASSISTANT_PROFILE: per-user preferences JSON. ASSISTANT_MEMORY: user-saved
-- memories (manual source only in M3; auto distillation stays conditional).
-- All rows are isolated by USER_ID; business data is stored as references
-- (module + keys), never snapshots. Idempotent: create only if absent.

SET NOCOUNT ON;

DECLARE @GUARD NVARCHAR(400) = N'本脚本只能在 EOS.ERP 数据库内执行，当前库为 ' + DB_NAME() + N'。';
IF DB_NAME() <> N'EOS.ERP'
    THROW 50000, @GUARD, 1;

BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.ASSISTANT_PROFILE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ASSISTANT_PROFILE (
        [USER_ID] NVARCHAR(50) NOT NULL CONSTRAINT [PK_ASSISTANT_PROFILE] PRIMARY KEY,
        [PREF_JSON] NVARCHAR(MAX) NULL,
        [UPDATED_AT] DATETIME2(3) NOT NULL CONSTRAINT [DF_ASSISTANT_PROFILE_UPDATED] DEFAULT (SYSUTCDATETIME())
    );
END

IF OBJECT_ID(N'dbo.ASSISTANT_MEMORY', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ASSISTANT_MEMORY (
        [ID] BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT [PK_ASSISTANT_MEMORY] PRIMARY KEY,
        [USER_ID] NVARCHAR(50) NOT NULL,
        [MEMORY_TYPE] NVARCHAR(20) NOT NULL CONSTRAINT [DF_ASSISTANT_MEMORY_TYPE] DEFAULT (N'fact'),
        [MEMORY_KEY] NVARCHAR(200) NOT NULL,
        [MEMORY_VALUE] NVARCHAR(MAX) NOT NULL,
        [SOURCE] NVARCHAR(20) NOT NULL CONSTRAINT [DF_ASSISTANT_MEMORY_SOURCE] DEFAULT (N'manual'),
        [SOURCE_MESSAGE_ID] BIGINT NULL,
        [CONFIDENCE] TINYINT NULL,
        [STATUS] NVARCHAR(20) NOT NULL CONSTRAINT [DF_ASSISTANT_MEMORY_STATUS] DEFAULT (N'active'),
        [CREATED_AT] DATETIME2(3) NOT NULL CONSTRAINT [DF_ASSISTANT_MEMORY_CREATED] DEFAULT (SYSUTCDATETIME()),
        [UPDATED_AT] DATETIME2(3) NOT NULL CONSTRAINT [DF_ASSISTANT_MEMORY_UPDATED] DEFAULT (SYSUTCDATETIME()),
        [LAST_ACCESSED_AT] DATETIME2(3) NOT NULL CONSTRAINT [DF_ASSISTANT_MEMORY_ACCESSED] DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT [CK_ASSISTANT_MEMORY_TYPE] CHECK ([MEMORY_TYPE] IN (N'preference', N'fact', N'favorite')),
        CONSTRAINT [CK_ASSISTANT_MEMORY_SOURCE] CHECK ([SOURCE] IN (N'manual', N'auto')),
        CONSTRAINT [CK_ASSISTANT_MEMORY_STATUS] CHECK ([STATUS] IN (N'active', N'pending', N'archived'))
    );
    CREATE INDEX [IX_ASSISTANT_MEMORY_USER_STATUS]
        ON dbo.ASSISTANT_MEMORY ([USER_ID], [STATUS], [LAST_ACCESSED_AT] DESC);
END

COMMIT TRANSACTION;

PRINT N'[043] 助手跨会话记忆表已就绪（ASSISTANT_PROFILE / ASSISTANT_MEMORY）。';
